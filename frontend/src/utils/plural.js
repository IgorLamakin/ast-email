// Склонение числительных по правилам русского языка (2.6.0).
//
// Зачем отдельный модуль: подсказки в выпадающих списках показывают «использован
// N раз», и при N=2 в интерфейсе появлялось «использован 2 раз». Склонение -
// чистая функция без React, поэтому она живёт здесь и покрыта node-тестами
// (frontend/tests/plural.test.js), а не проверяется глазами в собранном приложении.

/**
 * Выбирает форму слова для числа N по правилам русского языка.
 *
 * pluralRu(1, 'раз', 'раза', 'раз')   -> 'раз'
 * pluralRu(2, 'раз', 'раза', 'раз')   -> 'раза'
 * pluralRu(5, 'раз', 'раза', 'раз')   -> 'раз'
 * pluralRu(11, 'раз', 'раза', 'раз')  -> 'раз'  (вторая сотня не склоняется)
 * pluralRu(22, 'раз', 'раза', 'раз')  -> 'раза'
 */
export function pluralRu(count, one, few, many) {
  const n = Math.abs(Number(count) || 0) % 100
  const last = n % 10
  if (n > 10 && n < 20) return many
  if (last > 1 && last < 5) return few
  if (last === 1) return one
  return many
}

/**
 * Человеческая подпись к счётчику использования адреса отправителя:
 * 1 -> «использован 1 раз», 2 -> «использован 2 раза», 5 -> «использован 5 раз».
 */
export function usedTimesLabel(count) {
  const n = Number(count) || 0
  return 'использован ' + n + ' ' + pluralRu(n, 'раз', 'раза', 'раз')
}
